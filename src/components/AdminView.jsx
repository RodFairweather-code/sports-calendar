import { useState } from 'react'
import PatternsView from './PatternsView'
import StaffView from './StaffView'
import PlatformsView from './PlatformsView'
import TechStackView from './TechStackView'
import RightsView from './RightsView'
import BookableAssetsView from './BookableAssetsView'
import { saveToStorage } from '../services/storage'

const ROLE_KEYS = [
  { key: 'cameramen',               label: 'Cameramen' },
  { key: 'onsiteAudio',             label: 'Onsite Audio' },
  { key: 'onsiteProductionManager', label: 'Onsite Production Manager' },
  { key: 'director',                label: 'Director' },
  { key: 'producer',                label: 'Producer' },
  { key: 'commentator',             label: 'Commentator' },
  { key: 'evsOperator',             label: 'EVS Operator' },
  { key: 'graphicsOperator',        label: 'Graphics Operator' },
  { key: 'mamCheckers',             label: 'MAM Checkers' },
]

const CAP_KEYS = ['cam2', 'cam4', 'cam8plus', 'studio', 'tennis', 'rugby']

function buildSnapshot() {
  const staff    = JSON.parse(localStorage.getItem('admin_staff')          || '{}')
  const profiles = JSON.parse(localStorage.getItem('admin_staff_profiles') || '{}')
  const date     = new Date().toISOString().slice(0, 10)

  const lines = []
  lines.push(`// Sports Calendar — Staff Seed Data`)
  lines.push(`// Generated by the Snapshot button in Admin.`)
  lines.push(`// To update: press Snapshot, replace this file with the downloaded seedStaff.js, then commit.`)
  lines.push(`// Applied on first load only when localStorage has no staff data.`)
  lines.push(`// Last snapshot: ${date}`)
  lines.push(``)
  lines.push(`export const SEED_STAFF = {`)

  for (const { key } of ROLE_KEYS) {
    const names = staff[key] || []
    lines.push(`  ${key}: [${names.map(n => `'${n.replace(/'/g, "\\'")}'`).join(', ')}],`)
  }

  lines.push(`}`)
  lines.push(``)
  lines.push(`export const SEED_STAFF_PROFILES = {`)

  for (const { key } of ROLE_KEYS) {
    const names = staff[key] || []
    if (!names.length) continue

    lines.push(`  ${key}: {`)
    for (const name of names) {
      const p       = profiles[key]?.[name] || {}
      const caps    = p.caps || {}
      const capStr  = CAP_KEYS.map(c => `${c}: ${caps[c] ? 'true' : 'false'}`).join(', ')
      const isStaff   = p.isStaff !== false ? 'true' : 'false'
      const email     = (p.email || '').replace(/'/g, "\\'")
      const seniority = p.seniority || 1
      lines.push(`    '${name.replace(/'/g, "\\'")}': { isStaff: ${isStaff}, email: '${email}', seniority: ${seniority}, caps: { ${capStr} } },`)
    }
    lines.push(`  },`)
  }

  lines.push(`}`)
  return lines.join('\n')
}

