function downloadText(filename, content) {
  const blob = new Blob([content], { type: 'text/plain' })
  const url  = URL.createObjectURL(blob)
  const a    = document.createElement('a')
  a.href     = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}

function AdminView({ snapshotUnlocked, allEvents, onNavigate, onActivateComps }) {
  const [adminTab, setAdminTab] = useState('patterns')

  function handleSnapshot() {
    downloadText('seedStaff.js', buildSnapshot())
  }

  function handleSnapshotPatterns() {
    downloadText('seedPatterns.js', buildPatternsSnapshot())
  }

  function handleSnapshotRights() {
    downloadText('seedRights.js', buildRightsSnapshot())
  }

  function handleSnapshotAssets() {
    downloadText('seedBookableAssets.js', buildAssetsSnapshot())
  }

  function handleInitAll() {
    const decisions = JSON.parse(localStorage.getItem('editorial_decisions') || '{}')
    for (const event of allEvents) {
      if (!decisions[event.id]) decisions[event.id] = {}
      decisions[event.id].initProduction = true
    }
    if (!saveToStorage('editorial_decisions', decisions)) return
    alert(`Init Production set for all ${allEvents.length} events.`)
  }

  function handleInitSelected() {
    const platforms = JSON.parse(localStorage.getItem('admin_platforms') || '[]')
    const platformIds = platforms.map(p => p.id)
    const decisions = JSON.parse(localStorage.getItem('editorial_decisions') || '{}')

    let selectedCount = 0
    for (const event of allEvents) {
      const eventDecisions = decisions[event.id] || {}
      const hasSelection = platformIds.some(id => eventDecisions[id] === 'Y' || eventDecisions[id] === 'P')
      if (!decisions[event.id]) decisions[event.id] = {}
      decisions[event.id].initProduction = hasSelection
      if (hasSelection) selectedCount++
    }
    if (!saveToStorage('editorial_decisions', decisions)) return
    alert(`Init Production cleared, then set for ${selectedCount} event(s) selected on at least one platform.`)
  }

  function handleClearAllInit() {
    const decisions = JSON.parse(localStorage.getItem('editorial_decisions') || '{}')
    for (const event of allEvents) {
      if (decisions[event.id]) decisions[event.id].initProduction = false
    }
    if (!saveToStorage('editorial_decisions', decisions)) return
    alert(`Init Production cleared for all ${allEvents.length} events.`)
  }

  function handleTamsAll() {
    const platforms = JSON.parse(localStorage.getItem('admin_platforms') || '[]')
    const tams = platforms.find(p => p.name?.toLowerCase() === 'tams')
    if (!tams) { alert('No platform named "TAMS" found. Add it in Admin → Platforms first.'); return }

    const decisions = JSON.parse(localStorage.getItem('editorial_decisions') || '{}')
    for (const event of allEvents) {
      if (!decisions[event.id]) decisions[event.id] = {}
      decisions[event.id][tams.id] = 'Y'
    }
    if (!saveToStorage('editorial_decisions', decisions)) return
    alert(`TAMS set to Y for all ${allEvents.length} events.`)
  }

  function handleTamsSelected() {
    const platforms = JSON.parse(localStorage.getItem('admin_platforms') || '[]')
    const tams = platforms.find(p => p.name?.toLowerCase() === 'tams')
    if (!tams) { alert('No platform named "TAMS" found. Add it in Admin → Platforms first.'); return }

    const otherPlatformIds = platforms.filter(p => p.id !== tams.id).map(p => p.id)
    const decisions = JSON.parse(localStorage.getItem('editorial_decisions') || '{}')

    let definiteCount = 0
    let possibleCount = 0
    for (const event of allEvents) {
      const eventDecisions = decisions[event.id] || {}
      const values = otherPlatformIds.map(id => eventDecisions[id])
      const isDefinite = values.includes('Y')
      const isPossible = !isDefinite && values.includes('P')
      if (!decisions[event.id]) decisions[event.id] = {}
      decisions[event.id][tams.id] = isDefinite ? 'Y' : isPossible ? 'P' : ''
      if (isDefinite) definiteCount++
      if (isPossible) possibleCount++
    }
    if (!saveToStorage('editorial_decisions', decisions)) return
    alert(`TAMS cleared, then set to Y for ${definiteCount} definite event(s) and P for ${possibleCount} possible-only event(s).`)
  }

  function handleClearTams() {
    const platforms = JSON.parse(localStorage.getItem('admin_platforms') || '[]')
    const tams = platforms.find(p => p.name?.toLowerCase() === 'tams')
    if (!tams) { alert('No platform named "TAMS" found. Add it in Admin → Platforms first.'); return }

    const decisions = JSON.parse(localStorage.getItem('editorial_decisions') || '{}')
    for (const event of allEvents) {
      if (decisions[event.id]) decisions[event.id][tams.id] = ''
    }
    if (!saveToStorage('editorial_decisions', decisions)) return
    alert(`TAMS cleared for all ${allEvents.length} events.`)
  }

  function handleSelectMany() {
    const platforms = JSON.parse(localStorage.getItem('admin_platforms') || '[]')
    const findPlatform = name => platforms.find(p => p.name?.toLowerCase() === name.toLowerCase())
    const skyMcr = findPlatform('Sky MCR')
    const tams = findPlatform('TAMS')
    const itvEaling = findPlatform('ITV Ealing')
    const bbc1 = findPlatform('BBC 1')

    const missing = [
      !skyMcr && 'Sky MCR',
      !tams && 'TAMS',
      !itvEaling && 'ITV Ealing',
      !bbc1 && 'BBC 1',
    ].filter(Boolean)
    if (missing.length) {
      alert(`Missing platform(s): ${missing.join(', ')}. Add them in Admin → Platforms first.`)
      return
    }

    const decisions = JSON.parse(localStorage.getItem('editorial_decisions') || '{}')
    const setDecision = (eventId, platformId, value) => {
      if (!decisions[eventId]) decisions[eventId] = {}
      decisions[eventId][platformId] = value
    }
    const eventsFor = competitionId => allEvents.filter(e => e.extendedProps?.competitionId === competitionId)
    const sample = (events, fraction) => events.filter(() => Math.random() < fraction)

    for (const event of eventsFor('championship_2627')) {
      setDecision(event.id, skyMcr.id, 'Y')
      setDecision(event.id, tams.id, 'Y')
    }
    for (const event of sample(eventsFor('league_one_2627'), 0.5)) {
      setDecision(event.id, skyMcr.id, 'Y')
    }
    for (const event of sample(eventsFor('league_two_2627'), 0.25)) {
      setDecision(event.id, skyMcr.id, 'Y')
    }
    for (const event of sample(eventsFor('atp_tour'), 0.5)) {
      setDecision(event.id, itvEaling.id, 'Y')
    }
    for (const event of eventsFor('atp_tour')) {
      setDecision(event.id, bbc1.id, 'Y')
    }
    for (const event of eventsFor('scottish_premiership')) {
      setDecision(event.id, bbc1.id, 'Y')
    }

    if (!saveToStorage('editorial_decisions', decisions)) return
    onActivateComps?.(['championship_2627', 'league_one_2627', 'league_two_2627', 'atp_tour', 'scottish_premiership'])
    onNavigate?.('editorial')
  }

  function handleClearMany() {
    if (!saveToStorage('editorial_decisions', {})) return
    alert('All editorial decisions cleared for every platform.')
  }

  return (
    <div className="admin-view">
      <div className="admin-content">
        {adminTab === 'patterns'   && <PatternsView />}
        {adminTab === 'staff'      && <StaffView allEvents={allEvents} />}
        {adminTab === 'platforms'  && <PlatformsView />}
        {adminTab === 'techstack'  && <TechStackView />}
        {adminTab === 'rights'     && <RightsView />}
        {adminTab === 'bookableAssets' && <BookableAssetsView />}
      </div>
      <div className="admin-bottom-bar">
        <button className={`admin-tab-btn${adminTab === 'patterns'  ? ' active' : ''}`} onClick={() => setAdminTab('patterns')}>Patterns</button>
        <button className={`admin-tab-btn${adminTab === 'staff'     ? ' active' : ''}`} onClick={() => setAdminTab('staff')}>Staff</button>
        <button className={`admin-tab-btn${adminTab === 'platforms' ? ' active' : ''}`} onClick={() => setAdminTab('platforms')}>Platforms</button>
        <button className={`admin-tab-btn${adminTab === 'techstack' ? ' active' : ''}`} onClick={() => setAdminTab('techstack')}>Tech Stack</button>
        <button className={`admin-tab-btn${adminTab === 'rights'    ? ' active' : ''}`} onClick={() => setAdminTab('rights')}>Rights</button>
        <button className={`admin-tab-btn${adminTab === 'bookableAssets' ? ' active' : ''}`} onClick={() => setAdminTab('bookableAssets')}>Bookable Assets</button>
        <div className="admin-snapshot-group">
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleSnapshot}
          >
            Snapshot
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleSnapshotPatterns}
          >
            Snapshot Patterns
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleSnapshotRights}
          >
            Snapshot Rights
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleSnapshotAssets}
          >
            Snapshot Assets
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleTamsAll}
          >
            TAMS All
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleTamsSelected}
          >
            TAMS selected
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleClearTams}
          >
            Clear TAMS
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleInitAll}
          >
            Init All
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleInitSelected}
          >
            Init selected
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleClearAllInit}
          >
            Clear All Init
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleSelectMany}
          >
            Select Many Events
          </button>
          <button
            className={`admin-tab-btn admin-snapshot-btn${snapshotUnlocked ? ' visible' : ''}`}
            disabled={!snapshotUnlocked}
            tabIndex={snapshotUnlocked ? 0 : -1}
            onClick={handleClearMany}
          >
            Clear Many Events
          </button>
        </div>
      </div>
    </div>
  )
}

export default AdminView
